def collect_following_text(element: Tag, parent: Tag, children: List, i: int, cfg: ParserConfig) -> str:
    """
    Collect text following the element for year detection.
    First tries immediate siblings, then tries parent's siblings if element is nested.
    
    Args:
        element: The italic-like element containing the case name
        parent: The parent whose children we're iterating
        children: List of children of parent
        i: Current index in children
        cfg: Parser configuration
        
    Returns:
        Combined text window for year detection
    """
    window_texts: List[str] = []
    
    # Strategy 1: Look at immediate following siblings (original approach)
    for j in range(i, min(i + cfg.lookahead_siblings, len(children))):
        following = children[j]
        text = (
            following.get_text(" ", strip=True)
            if isinstance(following, Tag)
            else str(following)
        )
        window_texts.append(text)
    
    window = "".join(window_texts)
    
    # Strategy 2: If no year found, ALWAYS check element's parent's siblings
    # This handles cases like: <font><strong>Case</strong></font> <font>[YEAR]</font>
    if not (cfg.year_token_re.search(window) or 
            cfg.us_year_token_re.search(window) or
            cfg.year_range_token_re.search(window) or
            cfg.unreported_citation_re.search(window) or
            cfg.simple_unreported_re.search(window)):  # NEW: Check for simple unreported too
        
        # Get the element's immediate parent (e.g., the <font> tag)
        element_parent = element.parent
        
        if element_parent:
            # Look at this parent's following siblings
            parent_sibling_texts: List[str] = []
            current_sibling = element_parent.next_sibling
            sibling_count = 0
            
            while current_sibling and sibling_count < cfg.lookahead_siblings:
                if isinstance(current_sibling, Tag):
                    parent_sibling_texts.append(current_sibling.get_text(" ", strip=True))
                elif isinstance(current_sibling, str):
                    parent_sibling_texts.append(str(current_sibling))
                
                current_sibling = current_sibling.next_sibling
                sibling_count += 1
            
            if parent_sibling_texts:
                # Append parent sibling text to window
                window = window + " " + "".join(parent_sibling_texts)
    
    return window

