@dataclass
class ParserConfig:
    # Tags/classes considered as "italic-like" case title chunks
    # UPDATED: Added "strong" to support bold case names
    italic_tags: Tuple[str, ...] = ("span", "em", "i", "strong")
    italic_classes: Tuple[str, ...] = ("font-italic",)

    # Header containers and header text extraction - ENHANCED to include Judg-X content divs
    header_container_tags: Tuple[str, ...] = ("div", "p")
    header_container_classes: Tuple[str, ...] = (
        "Judg-1",           # ADDED: Regular judgment content paragraphs
        "Judg-2",           # ADDED: Continuation paragraphs
        "Judg-3",           # ADDED: Further continuation paragraphs  
        "Judg-Heading-1",
        "Judg-Heading-2",
        "Judg-Heading-3",
        "Judg-Heading-4",
        "Judg-Heading-5",
    )
    header_text_span_classes: Tuple[str, ...] = ("font-weight-bold",)

    # How many following siblings to scan to find year fragments
    lookahead_siblings: int = 10

    # Regexes for case detection
    versus_pattern: re.Pattern = re.compile(r"\s+v\.?\s+|\s+vs\.?\s+", re.IGNORECASE)
    re_title_pattern: re.Pattern = re.compile(r"^\s*(?:Re|In\s+re|In\s+the\s+matter\s+of)\b", re.IGNORECASE)
    
    # Singapore-style year patterns (unchanged)
    year_token_re: re.Pattern = re.compile(r"([\[(])\s*(\d{4})\s*([\])])")
    year_token_filter: re.Pattern = re.compile(r"[\[(]\s*\d{4}\s*[\])]")
    
    # US-style year patterns (unchanged)
    us_year_token_re: re.Pattern = re.compile(r"\(([^,)]+),\s*(\d{4})\)")
    us_year_token_filter: re.Pattern = re.compile(r"\([^,)]+,\s*\d{4}\)")

    # FIXED: Year range patterns - now handles en-dashes (–), em-dashes (—), and hyphens (-)
    year_range_token_re: re.Pattern = re.compile(r"([\[(])\s*(\d{4})[-–—∶']\s*(\d{4})\s*([\])])")
    year_range_token_filter: re.Pattern = re.compile(r"[\[(]\s*\d{4}[-–—∶']\s*\d{4}\s*[\])]")

    # Unreported citation patterns - TWO variants:
    # 1. With year: (Criminal Case No 16 of 2009, unreported)
    unreported_citation_re: re.Pattern = re.compile(r"\(([^)]*(\d{4})[^)]*),\s*unreported\)", re.IGNORECASE)
    unreported_citation_filter: re.Pattern = re.compile(r"\([^)]*\d{4}[^)]*,\s*unreported\)", re.IGNORECASE)
    
    # 2. Simple form: (Unreported) or (unreported) - NEW!
    simple_unreported_re: re.Pattern = re.compile(r"\(unreported\)", re.IGNORECASE)
    simple_unreported_filter: re.Pattern = re.compile(r"\(unreported\)", re.IGNORECASE)

