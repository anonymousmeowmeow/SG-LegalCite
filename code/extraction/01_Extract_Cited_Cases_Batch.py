def normalize_whitespace(text: str) -> str:
    """
    Normalize whitespace in text by:
    1. Converting all whitespace characters to regular spaces
    2. Collapsing multiple consecutive spaces to single spaces
    3. Stripping leading/trailing whitespace
    """
    if not text or pd.isna(text):
        return ""
    
    # Replace all types of whitespace with regular spaces
    # This includes: \t, \n, \r, \xa0 (non-breaking space), etc.
    normalized = re.sub(r'\s+', ' ', str(text))
    
    # Strip leading/trailing whitespace
    return normalized.strip()


def count_tokens(text: str) -> int:
    """
    Count the number of tokens/words in a text string.
    
    Args:
        text: The text to count tokens in
    
    Returns:
        Number of tokens (words) in the text
    """
    if not text or pd.isna(text):
        return 0
    
    # Split by whitespace and filter out empty strings
    tokens = re.split(r'\s+', str(text).strip())
    tokens = [token for token in tokens if token]  # Remove empty strings
    return len(tokens)


def filter_by_minimum_tokens(df: pd.DataFrame, min_tokens: int = 50, column: str = "Paragraph") -> pd.DataFrame:
    """
    Filter dataframe to remove rows where the specified column has fewer than min_tokens.
    Also removes cases where the paragraph is just the case name (insufficient context).
    
    Args:
        df: The dataframe to filter
        min_tokens: Minimum number of tokens required (default: 50 for substantial content)
        column: Column name to check token count (default: "Paragraph")
    
    Returns:
        Filtered dataframe with rows containing sufficient tokens and actual content
    """
    if column not in df.columns:
        return df
    
    # Count tokens for each row
    df['_token_count'] = df[column].apply(count_tokens)
    
    # Additional check: ensure paragraph contains more than just the case name
    def has_substantial_content(row):
        paragraph = str(row[column]).strip()
        case_name = str(row.get('Cited Case', '')).strip()
        
        # Remove the case name from paragraph to see what's left
        case_name_clean = re.sub(r'\s*\[.*?\]|\s*\(.*?\)', '', case_name).strip()
        
        # Check if paragraph is essentially just the case name
        if case_name_clean and len(case_name_clean) > 10:  # Only for substantial case names
            # If removing the case name leaves very little content, it's insufficient
            remaining_content = paragraph.replace(case_name_clean, '').strip()
            remaining_tokens = count_tokens(remaining_content)
            
            # Require at least 30 tokens beyond the case name
            return remaining_tokens >= 30
        
        return True  # For short case names, rely on token count only
    
    df['_has_content'] = df.apply(has_substantial_content, axis=1)
    
    # Filter to keep only rows with sufficient tokens AND substantial content
    filtered_df = df[(df['_token_count'] >= min_tokens) & (df['_has_content'])].copy()
    
    # Remove the temporary columns
    filtered_df = filtered_df.drop(columns=['_token_count', '_has_content'])
    
    return filtered_df

