async def _fetch_html_async(url: str, wait_selector: Optional[str] = None) -> str:
    from playwright.async_api import async_playwright

    async with async_playwright() as pw:
        browser = await pw.chromium.launch(headless=True)
        page = await browser.new_page()  # ✅ Correct - browser has new_page()
        await page.goto(url)
        if wait_selector:
            await page.wait_for_selector(wait_selector)
        html = await page.content()
        await browser.close()
        return html

def fetch_html(url: str, wait_selector: Optional[str] = None) -> str:
    return asyncio.get_event_loop().run_until_complete(_fetch_html_async(url, wait_selector))

