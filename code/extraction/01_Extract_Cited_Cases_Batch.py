def is_italic_like(tag: Tag, cfg: ParserConfig) -> bool:
    if not isinstance(tag, Tag):
        return False
    # UPDATED: Now checks for "em", "i", and "strong" tags
    if tag.name in ("em", "i", "strong"):
        return True
    if tag.name == "span" and any(cls in (tag.get("class") or []) for cls in cfg.italic_classes):
        return True
    return False


def is_header_container(tag: Tag, cfg: ParserConfig) -> bool:
    if not isinstance(tag, Tag):
        return False
    if tag.name not in cfg.header_container_tags:
        return False
    classes = tag.get("class", [])
    return any(cls in classes for cls in cfg.header_container_classes)


def is_judg_content_div(tag: Tag) -> bool:
    """Check if a tag is a Judg content div (Judg-1, Judg-2, etc.) but not a heading"""
    if not isinstance(tag, Tag):
        return False
    if tag.name not in ("div", "p"):
        return False
    classes = tag.get("class", [])
    # Match Judg-1, Judg-2, etc. but not Judg-Heading-X
    return any(re.match(r"^Judg-\d+$", cls) for cls in classes)


def is_judg_quote_div(tag: Tag) -> bool:
    """Check if a tag is a Judg quote div (Judg-Quote-0, Judg-Quote-1, etc.)"""
    if not isinstance(tag, Tag):
        return False
    if tag.name not in ("div", "p"):
        return False
    classes = tag.get("class", [])
    # Match Judg-Quote-0, Judg-Quote-1, etc.
    return any(re.match(r"^Judg-Quote-\d+$", cls) for cls in classes)


def is_judg_heading_div(tag: Tag) -> bool:
    """Check if a tag is a Judg heading div (Judg-Heading-X)"""
    if not isinstance(tag, Tag):
        return False
    if tag.name not in ("div", "p"):
        return False
    classes = tag.get("class", [])
    return any("Judg-Heading" in cls for cls in classes)


def extract_focused_case_paragraph(italic_element: Tag, case_name: str, context_paragraphs: int = 5, include_quotes: bool = True) -> str:
    """
    ENHANCED: Extract the specific paragraph containing the case + surrounding context + optional quotes.
    Works with both Judg-X structured documents and plain paragraph documents.
    
    Args:
        italic_element: The italic element containing the case name
        case_name: The case name (for debugging)
        context_paragraphs: Number of paragraphs before/after to include (default: 5)
        include_quotes: Whether to include consecutive quote divs after context (default: True)
    
    Returns:
        Combined text with focused paragraph, context, and optional quotes
    """
    
    # Step 1: Find the containing paragraph - try Judg divs first, then fall back to p/div tags
    containing_div = italic_element
    while containing_div and not (is_judg_content_div(containing_div) or is_judg_quote_div(containing_div)):
        containing_div = containing_div.find_parent()
    
    # If no Judg div found, look for a regular paragraph or div container
    if not containing_div:
        containing_div = italic_element
        while containing_div and containing_div.name not in ('p', 'div', 'blockquote'):
            containing_div = containing_div.find_parent()
    
    if not containing_div:
        # Last resort fallback: get immediate parent text
        parent = italic_element.find_parent()
        return parent.get_text(" ", strip=True) if parent else ""
    
    # Step 2: Get text from the containing paragraph
    main_paragraph = containing_div.get_text(" ", strip=True)
    context_parts = [main_paragraph]
    
    # Step 3: Add context from surrounding paragraphs
    if context_paragraphs > 0:
        # Define what counts as a sibling paragraph
        def is_paragraph_like(t):
            if is_judg_content_div(t) or is_judg_quote_div(t):
                return True
            # For non-Judg documents, accept p, div, blockquote tags
            return isinstance(t, Tag) and t.name in ('p', 'div', 'blockquote') and t.get_text(strip=True)
        
        # Add previous paragraphs
        current = containing_div
        for _ in range(context_paragraphs):
            prev_div = current.find_previous_sibling(is_paragraph_like)
            if prev_div:
                context_parts.insert(0, prev_div.get_text(" ", strip=True))
                current = prev_div
            else:
                break
        
        # Add following paragraphs
        current = containing_div
        for _ in range(context_paragraphs):
            next_div = current.find_next_sibling(is_paragraph_like)
            if next_div:
                context_parts.append(next_div.get_text(" ", strip=True))
                current = next_div
            else:
                break
    
    # Step 4: ENHANCED - Include consecutive quote divs if enabled (primarily for Judg-X documents)
    if include_quotes:
        # Find the last element we've collected so far
        last_element = containing_div
        
        # If we added following paragraphs, find the actual last element
        if context_paragraphs > 0:
            temp_current = containing_div
            for _ in range(context_paragraphs):
                next_div = temp_current.find_next_sibling(lambda t: is_judg_content_div(t) or is_judg_quote_div(t))
                if next_div:
                    last_element = next_div
                    temp_current = next_div
                else:
                    break
        
        # Now continue from last_element to collect consecutive quote divs
        current = last_element
        while True:
            next_div = current.find_next_sibling(lambda t: is_judg_content_div(t) or is_judg_quote_div(t))
            if next_div and is_judg_quote_div(next_div):
                # Only add if it's a quote div and not already included
                quote_text = next_div.get_text(" ", strip=True)
                if quote_text not in context_parts:  # Avoid duplicates
                    context_parts.append(quote_text)
                current = next_div
            else:
                # Stop if we hit a non-quote div or no more divs
                break
    
    # Step 5: Combine and return
    combined_text = " ".join(context_parts)
    return normalize_whitespace(combined_text)


def normalize_brackets(open_b: str) -> str:
    return "]" if open_b == "[" else ")"


def remove_year(casename: str, cfg: ParserConfig) -> str:
    # Remove Singapore, US style, year range, and unreported years
    temp = re.sub(cfg.year_token_filter, "", casename)
    temp = re.sub(cfg.us_year_token_filter, "", temp)
    temp = re.sub(cfg.year_range_token_filter, "", temp)  
    temp = re.sub(cfg.unreported_citation_filter, "", temp)  # Remove unreported with year
    temp = re.sub(cfg.simple_unreported_filter, "", temp)   # NEW: Remove simple unreported
    return temp.strip()


def re_group_key(title: str) -> Optional[str]:
    m = re.match(r"^\s*(?:Re|In\s+re|In\s+the\s+matter\s+of)\s+(.+)$", title, re.IGNORECASE)
    if not m:
        return None
    body = m.group(1)
    tokens = re.findall(r"[A-Za-z0-9&][A-Za-z0-9&.'-]*", body)
    if not tokens:
        return None
    return ("re " + tokens[0].lower())

