def extract_cases_from_soup(soup: BeautifulSoup, cfg: ParserConfig) -> pd.DataFrame:
    results = []
    processed_elements = set()  # Track processed elements to avoid duplicates

    # NEW APPROACH: Find all italic-like elements globally, regardless of nesting
    all_italic_elements = []
    for tag_name in cfg.italic_tags:
        all_italic_elements.extend(soup.find_all(tag_name))
    
    # Also find spans with italic classes
    for class_name in cfg.italic_classes:
        all_italic_elements.extend(soup.find_all("span", class_=class_name))
    
    for element in all_italic_elements:
        # Skip if already processed
        if id(element) in processed_elements:
            continue
        
        if not is_italic_like(element, cfg):
            continue
            
        first_italic_element = element
        italic_chunks = [element.get_text(" ", strip=True)]
        processed_elements.add(id(element))
        
        # Look for consecutive italic-like siblings to join multi-part case names
        current = element
        while True:
            next_sibling = current.next_sibling
            
            # Skip whitespace-only text nodes
            while next_sibling and isinstance(next_sibling, str) and next_sibling.strip() == "":
                next_sibling = next_sibling.next_sibling
            
            if next_sibling and isinstance(next_sibling, Tag) and is_italic_like(next_sibling, cfg):
                italic_chunks.append(next_sibling.get_text(" ", strip=True))
                processed_elements.add(id(next_sibling))
                current = next_sibling
            else:
                break
        
        full_case = " ".join(italic_chunks).strip()

        # ENHANCED: Use conservative Re case detection
        is_valid, final_case_name = is_valid_case_with_re_check(full_case, first_italic_element, cfg)

        if is_valid:
            # NEW: Enhanced year search with parent sibling fallback
            # Get siblings by looking at parent's children
            parent = element.parent
            if parent:
                children = list(parent.children)
                try:
                    element_index = children.index(element)
                    window = collect_following_text(element, parent, children, element_index + 1, cfg)
                except ValueError:
                    # Element not found in parent's children (shouldn't happen, but handle gracefully)
                    window = ""
            else:
                window = ""

            # Check for Singapore-style year first
            match = cfg.year_token_re.search(window)
            bracketed_year = None
            if match:
                open_b, yr, close_b = match.groups()
                bracketed_year = f"{open_b}{yr}{normalize_brackets(open_b)}"
            
            # Check for US-style year if no Singapore-style found
            if not bracketed_year:
                us_match = cfg.us_year_token_re.search(window)
                if us_match:
                    bracketed_year = us_match.group(0)

            # Check for year range if no other year found
            if not bracketed_year:
                year_range_match = cfg.year_range_token_re.search(window)
                if year_range_match:
                    open_b, start_yr, end_yr, close_b = year_range_match.groups()
                    bracketed_year = f"{open_b}{start_yr}-{end_yr}{normalize_brackets(open_b)}"

            # Check for unreported citations if no other year found
            if not bracketed_year:
                unreported_match = cfg.unreported_citation_re.search(window)
                if unreported_match:
                    bracketed_year = unreported_match.group(0)
            
            # NEW: Check for simple unreported (Unreported) if no other year found
            if not bracketed_year:
                simple_unreported_match = cfg.simple_unreported_re.search(window)
                if simple_unreported_match:
                    bracketed_year = simple_unreported_match.group(0)

            # Use the final_case_name (which might include "Re" prefix)
            case_output = f"{final_case_name} {bracketed_year}" if bracketed_year else final_case_name

            # ENHANCED: Extract focused paragraph with increased context and quote inclusion
            paragraph_block = extract_focused_case_paragraph(
                element, 
                case_output, 
                context_paragraphs=5,
                include_quotes=True
            )

            results.append({
                "Cited Case": case_output,
                "Paragraph": paragraph_block,
            })

    if not results:
        return pd.DataFrame(columns=["Cited Case", "Paragraph"])

    df = pd.DataFrame(results)

    # Check for Singapore, US style, year range, and unreported years
    has_singapore_year = df["Cited Case"].str.contains(cfg.year_token_filter, na=False)
    has_us_year = df["Cited Case"].str.contains(cfg.us_year_token_filter, na=False)
    has_year_range = df["Cited Case"].str.contains(cfg.year_range_token_filter, na=False)
    has_unreported = df["Cited Case"].str.contains(cfg.unreported_citation_filter, na=False)
    has_simple_unreported = df["Cited Case"].str.contains(cfg.simple_unreported_filter, na=False)  # NEW
    df["Has Year"] = has_singapore_year | has_us_year | has_year_range | has_unreported | has_simple_unreported  # NEW: Include simple unreported
    
    df["_is_re"] = df["Cited Case"].str.match(r"^\s*(?:Re|In\s+re|In\s+the\s+matter\s+of)\b", case=False)

    def base_group(x: str) -> Optional[str]:
        if not isinstance(x, str):
            return None
        return remove_year(x, cfg).lower()

    df["_group"] = df["Cited Case"].where(~df["_is_re"]).apply(base_group)

    re_keys = df.loc[df["_is_re"], "Cited Case"].apply(re_group_key)
    df.loc[df["_is_re"], "_group"] = re_keys

    # Simplified dedup key (no header)
    df["_dedup_key"] = df["_group"].astype(str)

    df.sort_values(by=["_dedup_key", "Has Year"], ascending=[True, False], inplace=True)

    clean_df = (
        df.drop_duplicates(subset=["_dedup_key"], keep="first")
          .drop(columns=["_group", "_dedup_key", "_is_re", "Has Year"])
    )

    # Filter to keep cases with Singapore, US style, year range, or unreported years
    has_singapore_year_final = clean_df["Cited Case"].str.contains(cfg.year_token_filter, na=False)
    has_us_year_final = clean_df["Cited Case"].str.contains(cfg.us_year_token_filter, na=False)
    has_year_range_final = clean_df["Cited Case"].str.contains(cfg.year_range_token_filter, na=False)
    has_unreported_final = clean_df["Cited Case"].str.contains(cfg.unreported_citation_filter, na=False)
    has_simple_unreported_final = clean_df["Cited Case"].str.contains(cfg.simple_unreported_filter, na=False)  # NEW
    clean_df = clean_df[has_singapore_year_final | has_us_year_final | has_year_range_final | has_unreported_final | has_simple_unreported_final].copy()

    # NEW: Post-extraction whitespace normalization
    for column in ["Cited Case", "Paragraph"]:
        if column in clean_df.columns:
            clean_df[column] = clean_df[column].apply(normalize_whitespace)
    
    # NEW: Filter out cases with insufficient paragraph content (< 50 tokens + substantial content check)
    # Prevents cases where paragraph is just the case name itself
    clean_df = filter_by_minimum_tokens(clean_df, min_tokens=50, column="Paragraph")
    
    return clean_df


def extract_cases_from_html(html: str, cfg: Optional[ParserConfig] = None) -> pd.DataFrame:
    cfg = cfg or ParserConfig()
    try:
        soup = BeautifulSoup(html, "html.parser")
    except Exception:
        soup = BeautifulSoup(html, "html.parser")
    return extract_cases_from_soup(soup, cfg)


def extract_cases_from_url(url: str, cfg: Optional[ParserConfig] = None, wait_selector: Optional[str] = None) -> pd.DataFrame:
    html = fetch_html(url, wait_selector=wait_selector)
    return extract_cases_from_html(html, cfg)

