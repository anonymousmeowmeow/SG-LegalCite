# ─────────────────────────── PROGRESS ────────────────────────────────────────

def load_progress():
    if os.path.exists(PROGRESS_FILE):
        try:
            with open(PROGRESS_FILE) as f:
                return json.load(f)
        except Exception:
            pass
    return None

def save_progress(last_index: int, last_reference: str, successful: int, failed: int, failed_refs: list):
    with open(PROGRESS_FILE, "w") as f:
        json.dump({
            "last_index":     last_index,
            "last_reference": last_reference,
            "timestamp":      datetime.now().isoformat(),
            "successful":     successful,
            "failed":         failed,
            "failed_refs":    failed_refs
        }, f, indent=2)

def clear_progress():
    if os.path.exists(PROGRESS_FILE):
        os.remove(PROGRESS_FILE)

# ─────────────────────────── MAIN ────────────────────────────────────────────

def main():
    print("=" * 65)
    print("SG-LEGALCITE — STEP 1: EXTRACT CITED CASES (BATCH)")
    print("=" * 65)

    # Load case index
    print(f"\nReading case index: {CASE_INDEX_FILE}")
    df_cases = pd.read_csv(CASE_INDEX_FILE)
    print(f"Total judgments: {len(df_cases)}")

    # Check for previous progress
    start_idx   = 0
    successful  = 0
    failed      = 0
    failed_refs = []

    prev = load_progress()
    if prev:
        print(f"\nPrevious progress found:")
        print(f"  Last processed : #{prev['last_index']} — {prev['last_reference']}")
        print(f"  Successful     : {prev['successful']}")
        print(f"  Failed         : {prev['failed']}")
        print(f"  Timestamp      : {prev['timestamp']}")
        print(f"\nOptions:")
        print(f"  1. Resume from #{prev['last_index'] + 1}")
        print(f"  2. Retry failed cases ({prev['failed']} cases)")
        print(f"  3. Start fresh")
        choice = input("\nEnter choice (1/2/3): ").strip()

        if choice == "1":
            start_idx   = prev["last_index"] + 1
            successful  = prev["successful"]
            failed      = prev["failed"]
            failed_refs = prev.get("failed_refs", [])
            df_cases    = df_cases.iloc[start_idx:]
            print(f"  Resuming from index #{start_idx}")
        elif choice == "2":
            failed_refs = prev.get("failed_refs", [])
            df_cases    = df_cases[df_cases["Full_Reference"].isin(failed_refs)]
            successful  = prev["successful"]
            failed      = 0
            failed_refs = []
            print(f"  Retrying {len(df_cases)} failed cases")
        else:
            clear_progress()
            print("  Starting fresh.")

    # Create output CSV with header if starting fresh
    if start_idx == 0 and not prev:
        with open(OUTPUT_FILE, 'w') as f:
            pass  # clear file

    cfg = ParserConfig()
    first_write = not os.path.exists(OUTPUT_FILE) or os.path.getsize(OUTPUT_FILE) == 0

    try:
        for i, (_, row) in enumerate(tqdm(df_cases.iterrows(), total=len(df_cases), desc="Extracting")):
            url       = row["URL"]
            ref       = row["Full_Reference"]
            abs_idx   = start_idx + i

            try:
                df_out = extract_cases_from_url(url, cfg)

                if df_out is not None and len(df_out) > 0:
                    # Filter out cited case names that are too long (garbage extractions)
                    before = len(df_out)
                    df_out = df_out[df_out['Cited Case'].astype(str).str.len() <= MAX_CITED_CASE_NAME_LENGTH]
                    filtered = before - len(df_out)

                    if filtered > 0 and len(df_out) > 0:
                        tqdm.write(f"  ✓ {ref}: {len(df_out)} cited cases extracted ({filtered} oversized filtered)")
                    elif filtered > 0 and len(df_out) == 0:
                        tqdm.write(f"  ⚠ {ref}: 0 cited cases after filtering {filtered} oversized names")
                    else:
                        tqdm.write(f"  ✓ {ref}: {len(df_out)} cited cases extracted")

                    # Add source judgment metadata
                    df_out.insert(0, "Judgment_URL",       url)
                    df_out.insert(1, "Judgment_Reference", ref)
                    df_out.insert(2, "Year",               row["Year"])
                    df_out.insert(3, "Court_Type",         row["Court_Type"])
                    df_out.insert(4, "Case_Number",        row["Case_Number"])

                    # Append to CSV (write header only on first write)
                    df_out.to_csv(OUTPUT_FILE, mode='a', header=first_write, index=False)
                    first_write = False
                    successful += 1
                else:
                    tqdm.write(f"  ⚠ No citations found: {ref}")
                    failed_refs.append(ref)
                    failed += 1

            except Exception as e:
                tqdm.write(f"  ✗ Error processing {ref}: {str(e)[:100]}")
                failed_refs.append(ref)
                failed += 1

            # Save progress every SAVE_EVERY judgments
            if (i + 1) % SAVE_EVERY == 0:
                save_progress(abs_idx, ref, successful, failed, failed_refs)

    except KeyboardInterrupt:
        print("\n\n⚠ Interrupted — saving progress...")
        save_progress(abs_idx, ref, successful, failed, failed_refs)

    # Final save
    save_progress(abs_idx, ref, successful, failed, failed_refs)

    print("\n" + "=" * 65)
    print("COMPLETE")
    print("=" * 65)
    print(f"Successful : {successful}")
    print(f"Failed     : {failed}")
    print(f"Output     : {OUTPUT_FILE}")

    if failed_refs:
        print(f"\nFailed cases:")
        for r in failed_refs:
            print(f"  - {r}")


if __name__ == "__main__":
    main()
