def check_for_re_prefix(element: Tag) -> Optional[str]:
    """
    CONSERVATIVE: Only check for specific "Re " pattern immediately before italic span.
    Returns the "Re " prefix if found, None otherwise.
    """
    # Get the immediate previous sibling
    prev_sibling = element.previous_sibling
    
    if isinstance(prev_sibling, str):
        # Check if it ends with "Re " (with space)
        text = str(prev_sibling).strip()
        if text.endswith(" Re") or text.endswith("Re"):
            # Only return "Re" if it's clearly a case prefix
            if re.search(r'\bRe\s*$', text):
                return "Re"
    
    return None


def is_valid_case_with_re_check(full_case: str, first_italic_element: Tag, cfg: ParserConfig) -> Tuple[bool, str]:
    """
    Check if text is a valid case, with special handling for split "Re" cases.
    Returns (is_valid, final_case_name)
    """
    # First, try the original patterns (unchanged)
    if cfg.versus_pattern.search(full_case) or cfg.re_title_pattern.match(full_case):
        return True, full_case
    
    # ONLY if original patterns fail, check for "Re" prefix
    re_prefix = check_for_re_prefix(first_italic_element)
    if re_prefix:
        combined_case = f"{re_prefix} {full_case}".strip()
        # Verify the combined text matches Re pattern
        if cfg.re_title_pattern.match(combined_case):
            return True, combined_case
    
    return False, full_case


